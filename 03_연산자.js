//논리 연산자
let boolA = true;
let boolB = false;

// or 연산자
// or 연산자는 연산에 참여하는 두 개의 피연산자 중 하나라도 참이면 참을 반환합니다.
console.log(boolA || boolB);
// and 연산자
// and 연산자는 연산에 참여하는 두 개의 피연산자 중 하나라도 거짓이면 거짓을 반환합니다.
console.log(boolA && boolB);

console.log(!boolA);
console.log(!boolB);
